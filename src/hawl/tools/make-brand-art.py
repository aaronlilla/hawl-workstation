"""Generates Hawl-branded replacements for the Orca onboarding art.
Run from the repo root: python src/hawl/tools/make-brand-art.py
Writes resources/onboarding/feature-wall/tile-NN.{gif,poster.jpg} (static Hawl cards, no Orca UI)
and resources/app-icons/orca-blue.png / orca-watercolor.png (two distinct Hawl icon variants;
file names kept so no code changes)."""
import re
import textwrap
from PIL import Image, ImageDraw, ImageFont, ImageFilter

FONTS = 'C:/Windows/Fonts/'
icon = Image.open('resources/icon.png').convert('RGBA')

# ---- app icon variants ----
def daylight():
    size = 512
    bg = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(bg)
    d.rounded_rectangle((20, 20, size - 20, size - 20), radius=110, fill=(255, 251, 242, 255), outline=(255, 107, 26, 255), width=10)
    art = icon.resize((380, 380), Image.LANCZOS)
    bg.alpha_composite(art, (66, 66))
    return bg

icon.save('resources/app-icons/orca-blue.png')
daylight().save('resources/app-icons/orca-watercolor.png')

# ---- feature wall cards ----
src = open('src/shared/feature-wall-tiles.ts', encoding='utf8').read()
tiles = []
for block in src.split("id: 'tile-")[1:]:
    tid = 'tile-' + block[:2]
    m = re.search(r"title: '((?:[^'\\]|\\.)*)'", block)
    c = re.search(r"caption:\s*'((?:[^'\\]|\\.)*)'", block) or re.search(r'caption:\s*"([^"]*)"', block)
    if m and c:
        tiles.append((tid, m.group(1), c.group(1)))
print([t[0] for t in tiles]); assert len(tiles) == 12, len(tiles)
W, H = 960, 540
title_f = ImageFont.truetype(FONTS + 'arialbd.ttf', 54)
cap_f = ImageFont.truetype(FONTS + 'arial.ttf', 28)
small_f = ImageFont.truetype(FONTS + 'arialbd.ttf', 22)
mark = icon.resize((150, 150), Image.LANCZOS)
for tid, title, caption in tiles:
    title = title.replace("\\'", "'").replace('Orca', 'Hawl')
    caption = caption.replace("\\'", "'").replace('Orca', 'Hawl')
    img = Image.new('RGB', (W, H), (255, 251, 242))
    d = ImageDraw.Draw(img)
    # warm glow top right
    glow = Image.new('RGB', (W, H), (255, 251, 242))
    gd = ImageDraw.Draw(glow)
    gd.ellipse((560, -220, 1180, 400), fill=(255, 190, 140))
    glow = glow.filter(ImageFilter.GaussianBlur(90))
    img = Image.blend(img, glow, 0.7)
    d = ImageDraw.Draw(img)
    d.rectangle((0, 0, 12, H), fill=(255, 107, 26))
    img.paste(mark, (W - 190, 40), mark)
    d.text((64, 56), 'HAWL WORKSTATION', font=small_f, fill=(255, 107, 26))
    y = 150
    for line in textwrap.wrap(title, 22):
        d.text((64, y), line, font=title_f, fill=(15, 31, 61))
        y += 66
    y += 14
    for line in textwrap.wrap(caption, 52):
        d.text((64, y), line, font=cap_f, fill=(70, 82, 105))
        y += 40
    base = f'resources/onboarding/feature-wall/{tid}'
    img.save(base + '.poster.jpg', quality=88)
    img.convert('P', palette=Image.ADAPTIVE, colors=128).save(base + '.gif')
    open(base + '.recorded-at.json', 'w').write('{\n  "recordedAtUnixSeconds": 1792368000,\n  "recordedAtIso": "2026-10-19T00:00:00.000Z",\n  "sourceGif": "generated by src/hawl/tools/make-brand-art.py",\n  "sourcePoster": "generated by src/hawl/tools/make-brand-art.py"\n}\n')
print('ok', len(tiles))
